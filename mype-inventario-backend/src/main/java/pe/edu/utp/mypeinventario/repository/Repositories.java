package pe.edu.utp.mypeinventario.repository;
import org.springframework.stereotype.Component;
import org.springframework.jdbc.core.JdbcTemplate;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.annotation.*;
import pe.edu.utp.mypeinventario.domain.*;
import java.util.*;
@Component public class Repositories {
 public final JdbcRepository<Comerciante> comerciantes;
 public final JdbcRepository<Usuario> usuarios;
 public final JdbcRepository<RolPermiso> rolesPermiso;
 public final JdbcRepository<Sucursal> sucursales;
 public final JdbcRepository<Notificacion> notificaciones;
 public final JdbcRepository<ProductoItem> productos;
 public final JdbcRepository<Categoria> categorias;
 public final JdbcRepository<Marca> marcas;
 public final JdbcRepository<ImagenProducto> imagenesProducto;
 public final JdbcRepository<EtiquetaProducto> etiquetasProducto;
 public final JdbcRepository<VarianteSKU> variantes;
 public final JdbcRepository<AtributoVariante> atributosVariante;
 public final JdbcRepository<CodigoBarras> codigosBarras;
 public final JdbcRepository<ListaPrecio> listasPrecio;
 public final JdbcRepository<DescuentoPromocion> descuentosPromocion;
 public final JdbcRepository<MovimientoInventario> movimientos;
 public final JdbcRepository<AlertaReabastecimiento> alertas;
 public final JdbcRepository<Almacen> almacenes;
 public final JdbcRepository<Lote> lotes;
 public final JdbcRepository<TipoMovimiento> tiposMovimiento;
 public final JdbcRepository<VentaPunto> ventas;
 public final JdbcRepository<ProveedorMayorista> proveedores;
 public final JdbcRepository<DetalleVenta> detallesVenta;
 public final JdbcRepository<MetodoPago> metodosPago;
 public final JdbcRepository<ComprobantePago> comprobantesPago;
 public Repositories(JdbcTemplate jdbc) {
  ObjectMapper mapper=new ObjectMapper();
  mapper.setVisibility(PropertyAccessor.ALL,JsonAutoDetect.Visibility.NONE);
  mapper.setVisibility(PropertyAccessor.FIELD,JsonAutoDetect.Visibility.ANY);
  jdbc.execute("CREATE TABLE IF NOT EXISTS comerciante (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  comerciantes=new JdbcRepository<>(jdbc,mapper,Comerciante.class,"comerciante",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS usuario (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  usuarios=new JdbcRepository<>(jdbc,mapper,Usuario.class,"usuario",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS rolpermiso (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  rolesPermiso=new JdbcRepository<>(jdbc,mapper,RolPermiso.class,"rolpermiso",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS sucursal (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  sucursales=new JdbcRepository<>(jdbc,mapper,Sucursal.class,"sucursal",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS notificacion (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  notificaciones=new JdbcRepository<>(jdbc,mapper,Notificacion.class,"notificacion",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS productoitem (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  productos=new JdbcRepository<>(jdbc,mapper,ProductoItem.class,"productoitem",columns("comerciante_id","comercianteId"));
  jdbc.execute("CREATE TABLE IF NOT EXISTS categoria (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  categorias=new JdbcRepository<>(jdbc,mapper,Categoria.class,"categoria",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS marca (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  marcas=new JdbcRepository<>(jdbc,mapper,Marca.class,"marca",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS imagenproducto (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  imagenesProducto=new JdbcRepository<>(jdbc,mapper,ImagenProducto.class,"imagenproducto",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS etiquetaproducto (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  etiquetasProducto=new JdbcRepository<>(jdbc,mapper,EtiquetaProducto.class,"etiquetaproducto",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS variantesku (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  variantes=new JdbcRepository<>(jdbc,mapper,VarianteSKU.class,"variantesku",columns("producto_id","productoId","codigo_barra","codigoBarra","stock_actual","stockActual","stock_minimo","stockMinimo","precio_venta","precioVenta"));
  jdbc.execute("CREATE TABLE IF NOT EXISTS atributovariante (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  atributosVariante=new JdbcRepository<>(jdbc,mapper,AtributoVariante.class,"atributovariante",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS codigobarras (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  codigosBarras=new JdbcRepository<>(jdbc,mapper,CodigoBarras.class,"codigobarras",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS listaprecio (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  listasPrecio=new JdbcRepository<>(jdbc,mapper,ListaPrecio.class,"listaprecio",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS descuentopromocion (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  descuentosPromocion=new JdbcRepository<>(jdbc,mapper,DescuentoPromocion.class,"descuentopromocion",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS movimientoinventario (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  movimientos=new JdbcRepository<>(jdbc,mapper,MovimientoInventario.class,"movimientoinventario",columns("variante_id","varianteId"));
  jdbc.execute("CREATE TABLE IF NOT EXISTS alertareabastecimiento (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  alertas=new JdbcRepository<>(jdbc,mapper,AlertaReabastecimiento.class,"alertareabastecimiento",columns("variante_id","varianteId","comerciante_id","comercianteId"));
  jdbc.execute("CREATE TABLE IF NOT EXISTS almacen (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  almacenes=new JdbcRepository<>(jdbc,mapper,Almacen.class,"almacen",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS lote (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  lotes=new JdbcRepository<>(jdbc,mapper,Lote.class,"lote",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS tipomovimiento (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  tiposMovimiento=new JdbcRepository<>(jdbc,mapper,TipoMovimiento.class,"tipomovimiento",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS ventapunto (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  ventas=new JdbcRepository<>(jdbc,mapper,VentaPunto.class,"ventapunto",columns("comerciante_id","comercianteId","total","total"));
  jdbc.execute("CREATE TABLE IF NOT EXISTS proveedormayorista (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  proveedores=new JdbcRepository<>(jdbc,mapper,ProveedorMayorista.class,"proveedormayorista",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS detalleventa (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  detallesVenta=new JdbcRepository<>(jdbc,mapper,DetalleVenta.class,"detalleventa",columns("venta_id","ventaId","variante_id","varianteId"));
  jdbc.execute("CREATE TABLE IF NOT EXISTS metodopago (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  metodosPago=new JdbcRepository<>(jdbc,mapper,MetodoPago.class,"metodopago",columns());
  jdbc.execute("CREATE TABLE IF NOT EXISTS comprobantepago (id VARCHAR(36) PRIMARY KEY,payload CLOB NOT NULL)");
  comprobantesPago=new JdbcRepository<>(jdbc,mapper,ComprobantePago.class,"comprobantepago",columns());
  jdbc.execute("ALTER TABLE productoitem ADD COLUMN IF NOT EXISTS comerciante_id VARCHAR(36) NOT NULL REFERENCES comerciante(id)");
  jdbc.execute("ALTER TABLE variantesku ADD COLUMN IF NOT EXISTS producto_id VARCHAR(36) NOT NULL REFERENCES productoitem(id)");
  jdbc.execute("ALTER TABLE variantesku ADD COLUMN IF NOT EXISTS codigo_barra VARCHAR(100) NOT NULL UNIQUE");
  jdbc.execute("ALTER TABLE variantesku ADD COLUMN IF NOT EXISTS stock_actual INTEGER NOT NULL CHECK (stock_actual>=0)");
  jdbc.execute("ALTER TABLE variantesku ADD COLUMN IF NOT EXISTS stock_minimo INTEGER NOT NULL CHECK (stock_minimo>=0)");
  jdbc.execute("ALTER TABLE variantesku ADD COLUMN IF NOT EXISTS precio_venta DECIMAL(14,2) NOT NULL CHECK (precio_venta>=0)");
  jdbc.execute("ALTER TABLE ventapunto ADD COLUMN IF NOT EXISTS comerciante_id VARCHAR(36) NOT NULL REFERENCES comerciante(id)");
  jdbc.execute("ALTER TABLE ventapunto ADD COLUMN IF NOT EXISTS total DECIMAL(14,2) NOT NULL CHECK (total>=0)");
  jdbc.execute("ALTER TABLE movimientoinventario ADD COLUMN IF NOT EXISTS variante_id VARCHAR(36) NOT NULL REFERENCES variantesku(id)");
  jdbc.execute("ALTER TABLE alertareabastecimiento ADD COLUMN IF NOT EXISTS variante_id VARCHAR(36) NOT NULL REFERENCES variantesku(id)");
  jdbc.execute("ALTER TABLE alertareabastecimiento ADD COLUMN IF NOT EXISTS comerciante_id VARCHAR(36) NOT NULL REFERENCES comerciante(id)");
  jdbc.execute("ALTER TABLE detalleventa ADD COLUMN IF NOT EXISTS venta_id VARCHAR(36) NOT NULL REFERENCES ventapunto(id)");
  jdbc.execute("ALTER TABLE detalleventa ADD COLUMN IF NOT EXISTS variante_id VARCHAR(36) NOT NULL REFERENCES variantesku(id)");
 }
 private static LinkedHashMap<String,String> columns(String... pairs) {
  var map=new LinkedHashMap<String,String>(); for(int i=0;i<pairs.length;i+=2) map.put(pairs[i],pairs[i+1]); return map;
 }
}
